// Current language code
window.currentLanguage = localStorage.getItem('kisan_lang') || 'en';

// Helper to get translated string
window.t = function(key) {
  const langObj = window.I18N_DICTIONARY[window.currentLanguage] || window.I18N_DICTIONARY.en;
  return langObj[key] || window.I18N_DICTIONARY.en[key] || key;
};

// Instant Dynamic DOM Translation (Zero Page Reloads)
window.setLanguage = function(langCode) {
  if (!window.I18N_DICTIONARY[langCode]) {
    langCode = 'en';
  }
  window.currentLanguage = langCode;
  localStorage.setItem('kisan_lang', langCode);

  const langObj = window.I18N_DICTIONARY[langCode] || window.I18N_DICTIONARY.en;

  // Translate text content for elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (langObj[key]) {
      el.textContent = langObj[key];
    } else if (window.I18N_DICTIONARY.en[key]) {
      el.textContent = window.I18N_DICTIONARY.en[key];
    }
  });

  // Translate placeholders for elements with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (langObj[key]) {
      el.setAttribute('placeholder', langObj[key]);
    } else if (window.I18N_DICTIONARY.en[key]) {
      el.setAttribute('placeholder', window.I18N_DICTIONARY.en[key]);
    }
  });

  // Translate titles/tooltips
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (langObj[key]) {
      el.setAttribute('title', langObj[key]);
    } else if (window.I18N_DICTIONARY.en[key]) {
      el.setAttribute('title', window.I18N_DICTIONARY.en[key]);
    }
  });

  // Synchronize language dropdown selects
  const langSelect = document.getElementById('globalLanguageSelect');
  if (langSelect && langSelect.value !== langCode) {
    langSelect.value = langCode;
  }

  // Update HTML lang attribute
  document.documentElement.lang = langCode;

  // Trigger any active component re-renders if necessary
  if (typeof window.refreshMandiTable === 'function') {
    window.refreshMandiTable();
  }
  if (typeof window.renderLotsDashboard === 'function') {
    window.renderLotsDashboard();
  }
  if (typeof window.renderWholesaleCatalog === 'function') {
    window.renderWholesaleCatalog();
  }
};
